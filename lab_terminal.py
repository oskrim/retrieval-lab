def rrf(k, *scores):
    """Reciprocal rank fusion: each list adds 1 / (k + rank) for every document; the scores themselves are dropped."""
    return sum(1 / (k + np.argsort(np.argsort(-s, axis=1), axis=1) + 1) for s in scores)

